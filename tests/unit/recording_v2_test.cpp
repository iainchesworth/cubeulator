constexpr std::string_view kSolvedText = "UUUUUUUUURRRRRRRRRFFFFFFFFFDDDDDDDDDLLLLLLLLLBBBBBBBBB";

// As a std::string, which is what the oracle takes (a namespace-scope
// std::string would allocate during static initialisation).
std::string solved_state() {
    return std::string(kSolvedText);
}

