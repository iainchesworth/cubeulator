const std::string kSolved = "UUUUUUUUURRRRRRRRRFFFFFFFFFDDDDDDDDDLLLLLLLLLBBBBBBBBB";

fs::path fresh_dir(const char* name) {
    const fs::path dir = fs::temp_directory_path() / "cubeulator-tests" / name;
    fs::remove_all(dir);
    fs::create_directories(dir);
    return dir;
}

