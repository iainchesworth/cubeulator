namespace cube::solver {

// Solves `scrambled` the way a speedcuber's CFOP method is structured: the
// cross, then the first two layers' corner-edge pairs, then the whole last
// layer's orientation, then its permutation. A third of the beginner
// method's moves (about 55 against 100) in the same four-stage shape a
// learner can go on to practise. This is the engine behind
// SolveMethod::Intermediate.
//
//   Cross  the four white edges, in the fewest moves there are.
//   F2l    the four corner-edge pairs, one at a time, always taking
//          whichever remaining pair is cheapest. Each is the shortest way
//          to slot it in that leaves the cross and the pairs already made
//          untouched, and it only turns the top, the pair's own slot, and
//          the slot(s) the pair's pieces are stuck in - the same
//          "get it out, then in" a person does.
//   Oll    every last-layer piece oriented, in one sequence.
//   Pll    every last-layer piece permuted, in one sequence.
//
// The last layer is read from a table (src/lib/src/solver/
// cfop_case_words.inc, generated by tools/cfop_tables): 216 orientation
// cases and 288 permutation cases, each the shortest sequence in
// <U, R, F>. There is no search there at all.
//
// Fails like solve_two_phase(): invalid_cube_state for a cube that is not
// physically valid, unsolvable_state for one that is valid but unreachable.
[[nodiscard]] Result<Solution> solve_cfop(const Cube& scrambled);

}  // namespace cube::solver
